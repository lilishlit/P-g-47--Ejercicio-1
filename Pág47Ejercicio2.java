public class Pág47Ejercicio2 {
    public static void main(String[] args) {
        // Cadena original
        String cadena = "200";
        
        // Conversión a entero en la variable E
        int E = Integer.parseInt(cadena);
        
        // Comprobación (opcional, solo para ver el resultado en consola)
        System.out.println("El valor de E es= " + E);
        
        // Sumamos 5 para demostrar que ya es un número y no texto
        System.out.println("Prueba de suma (E + 5): " + (E + 5));
        System.out.println("Prueba de resta (E - 5): " + (E - 5));
        System.out.println("Prueba con multiplicación (E * 5): " + (E * 5));
        }
}
